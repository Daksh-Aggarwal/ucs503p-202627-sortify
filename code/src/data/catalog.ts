export function locationGuidance(location: string, category: Category) {
  const stream =
    category === 'Organic'
      ? 'wet-waste and compost collection'
      : category === 'Recyclable'
        ? 'accepted dry-recycling materials'
        : category === 'E-waste'
          ? 'authorized e-waste take-back services'
          : category === 'Hazardous'
            ? 'specialist collection services'
            : 'general-waste collection';
  return `Confirm ${stream} with your local collector${location && location !== 'Location detected' ? ` in ${location}` : ''}. Verify local schedules with municipal authorities.`;
}

